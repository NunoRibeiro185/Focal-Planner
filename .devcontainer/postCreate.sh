#!/usr/bin/env bash
# Provisions the self-contained local environment after the devcontainer is built.
# Idempotent: safe to re-run with `bash .devcontainer/postCreate.sh`.
set -euo pipefail

cd "$(dirname "$0")/.."

echo "▶ Installing npm dependencies…"
npm ci

# Install the Supabase CLI deterministically (the devcontainers-extra feature's
# asset resolver breaks on Supabase's current release layout). Pinned to match
# the host CLI; the tarball asset is un-versioned: supabase_linux_<arch>.tar.gz.
SUPABASE_VERSION="2.75.0"
if ! command -v supabase >/dev/null 2>&1; then
  echo "▶ Installing Supabase CLI v${SUPABASE_VERSION}…"
  arch="$(dpkg --print-architecture)" # amd64 | arm64
  tmp="$(mktemp -d)"
  curl -fsSL "https://github.com/supabase/cli/releases/download/v${SUPABASE_VERSION}/supabase_linux_${arch}.tar.gz" -o "$tmp/supabase.tar.gz"
  tar -xzf "$tmp/supabase.tar.gz" -C "$tmp"
  sudo install -m 0755 "$tmp/supabase" /usr/local/bin/supabase
  rm -rf "$tmp"
fi
SUPABASE="supabase"

echo "▶ Starting local Supabase stack (first run pulls images — be patient)…"
$SUPABASE start

echo "▶ Applying migrations + seed to the local database…"
$SUPABASE db reset

echo "▶ Writing .env.local from the running stack…"
# `supabase status -o env` prints ANON_KEY="…", SERVICE_ROLE_KEY="…", etc.
# Prefix with SB_ so we can reference them without clobbering anything.
eval "$($SUPABASE status -o env | sed 's/^/SB_/')"

cat > .env.local <<EOF
# ─────────────────────────────────────────────────────────────────────────
# Generated by .devcontainer/postCreate.sh — LOCAL STACK ONLY.
# Gitignored. Contains no production credentials. Regenerate by re-running the
# postCreate script. Never points at the remote project.
# ─────────────────────────────────────────────────────────────────────────

# Browser hits the host-published Supabase port:
NEXT_PUBLIC_SUPABASE_URL=http://localhost:54321
# The in-container server reaches the same stack via the host gateway:
SUPABASE_INTERNAL_URL=http://host.docker.internal:54321
NEXT_PUBLIC_SUPABASE_ANON_KEY=${SB_ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SB_SERVICE_ROLE_KEY}

# Skip Google OAuth — server.ts resolves the seeded dev photographer instead.
DEV_BYPASS_AUTH=true
NEXT_PUBLIC_APP_URL=http://localhost:3000

# External services are stubbed offline; no real calls are made locally.
# Turnstile values are Cloudflare's "always passes" test keys.
RESEND_API_KEY=re_local_dummy
RESEND_FROM_ADDRESS=dev@localhost
NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA
TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA
LEMONSQUEEZY_API_KEY=local_dummy
LEMONSQUEEZY_WEBHOOK_SECRET=local_dummy
LEMONSQUEEZY_STORE_ID=0
GOOGLE_CLIENT_ID=local_dummy
GOOGLE_CLIENT_SECRET=local_dummy
GOOGLE_REDIRECT_URI=http://localhost:3000/auth/google/callback
EOF

cat <<'MSG'

✅ Local environment ready.

   npm run dev          → http://localhost:3000   (logged in as the seed user)
   Supabase Studio      → http://localhost:54323
   Inbucket (emails)    → http://localhost:54324

   Reset the DB to the seed at any time:  npm run db:reset
MSG
